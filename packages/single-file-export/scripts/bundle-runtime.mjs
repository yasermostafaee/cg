#!/usr/bin/env node
// Bundles @cg/template-runtime into `src/generated/cg-runtime-bundles.ts` — a
// generated TS module exporting the runtime as two strings:
//
//   cgJs      ESM  (chrome71) — the preview iframe + the .vcg. B-066: the
//                               .vcg's own index.html is a CasparCG-loadable
//                               page, so its bundle must PARSE on the CEF
//                               baseline too (es2022 syntax would SyntaxError
//                               on CEF 71 before any boot error could show);
//                               the preview runs the same output unchanged.
//   cgJsIife  IIFE (chrome71) — the file://-safe single-file CasparCG export
//                               (D-019). Targets the oldest supported CEF
//                               (CasparCG 2.3 LTS ≈ Chromium 71) and exposes
//                               `window.CG = { createRuntime, installCasparGlobals, … }`.
//
// B-066 — `target` lowers SYNTAX only: newer BUILT-IN METHODS (replaceAll…)
// pass through untouched. Method compat is enforced separately by the
// cef-compat lint (@cg/eslint-config) + the bundle-artifact scan
// (tests/cef-compat.test.ts), sharing one curated banned list.
//
// Emitting a TS module of string consts (vs a Vite `?raw` import) keeps the
// package bundler-agnostic — it builds to plain `dist` consumed by both apps.
//
// Same @cg/template-runtime source feeds both — only the bundle format/target
// differs, so what the Designer shows IS what CasparCG plays. Regenerated by the
// package's pre{build,typecheck,test} hooks; gitignored. Write is atomic.

import * as esbuild from 'esbuild';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = path.resolve(__dirname, '..');
const REPO_ROOT = path.resolve(PKG_ROOT, '..', '..');
const ENTRY = path.resolve(REPO_ROOT, 'packages/template-runtime/src/index.ts');
const OUT_DIR = path.resolve(PKG_ROOT, 'src/generated');
const OUT_FILE = path.join(OUT_DIR, 'cg-runtime-bundles.ts');

// D-125 §D5(c) — CONDITIONAL LOTTIE PLAYER. The `lottie_light` player is ~168 KB
// minified. Bundling it UNCONDITIONALLY would ship it into EVERY export (doubling
// the on-disk single-file every CEF reads from file://). Instead:
//   * The BASE runtime (`cgJs`/`cgJsIife`) resolves `@cg/lottie-bridge`'s
//     `lottie-web/build/player/lottie_light` import to a tiny STUB that delegates
//     `loadAnimation` to the global `__cgLottie` (installed by the player bundle).
//     So the base bundle is byte-unaffected by the player — a scene with no Lottie
//     never calls it.
//   * The PLAYER (`cgJsLottie`/`cgJsLottieIife`) is a SEPARATE minified bundle that
//     imports the real `lottie_light` and installs `globalThis.__cgLottie`. The
//     exporters APPEND it (before the runtime script) ONLY when the scene has a
//     Lottie element — so the base runtime then finds the real player on the global.
// Both the base and the player artifacts pass the CEF-compat scan (tests/cef-compat.test.ts).

const LOTTIE_LIGHT = 'lottie-web/build/player/lottie_light';
/** The base runtime's stub for the player import — delegates to the global. */
const LOTTIE_STUB = `export default { loadAnimation: function () {
  var L = globalThis.__cgLottie;
  if (!L) throw new Error('Lottie player bundle not loaded (no __cgLottie global)');
  return L.loadAnimation.apply(L, arguments);
} };`;
/** esbuild plugin: replace the real player with {@link LOTTIE_STUB} in the base build. */
const stubLottiePlugin = {
  name: 'stub-lottie',
  setup(build) {
    build.onResolve({ filter: new RegExp(`^${LOTTIE_LIGHT.replace(/\//g, '\\/')}$`) }, () => ({
      path: 'lottie-stub',
      namespace: 'lottie-stub',
    }));
    build.onLoad({ filter: /.*/, namespace: 'lottie-stub' }, () => ({
      contents: LOTTIE_STUB,
      loader: 'js',
    }));
  },
};

/** Bundle the BASE runtime (player stubbed) once and return its source text. */
async function bundle({ format, target, globalName }) {
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    bundle: true,
    format,
    platform: 'browser',
    target,
    ...(globalName !== undefined ? { globalName } : {}),
    write: false,
    minify: false,
    sourcemap: false,
    plugins: [stubLottiePlugin],
  });
  const out = result.outputFiles[0];
  if (!out) throw new Error(`esbuild produced no output for ${format}/${target}`);
  return out.text;
}

/** Bundle the standalone PLAYER (real lottie_light → `globalThis.__cgLottie`), minified. */
async function bundleLottiePlayer({ format, globalName }) {
  const result = await esbuild.build({
    stdin: {
      contents: `import lottie from '${LOTTIE_LIGHT}';\nglobalThis.__cgLottie = lottie;\n`,
      resolveDir: path.resolve(REPO_ROOT, 'packages/lottie-bridge'),
      sourcefile: 'lottie-player-entry.js',
      loader: 'js',
    },
    bundle: true,
    format,
    platform: 'browser',
    target: 'chrome71',
    ...(globalName !== undefined ? { globalName } : {}),
    write: false,
    minify: true,
    sourcemap: false,
  });
  const out = result.outputFiles[0];
  if (!out) throw new Error(`esbuild produced no lottie-player output for ${format}`);
  return out.text;
}

const cgJs = await bundle({ format: 'esm', target: 'chrome71' });
const cgJsIife = await bundle({ format: 'iife', target: 'chrome71', globalName: 'CG' });
const cgJsLottie = await bundleLottiePlayer({ format: 'esm' });
const cgJsLottieIife = await bundleLottiePlayer({ format: 'iife', globalName: 'CGLottie' });

// JSON.stringify yields a valid, fully-escaped JS string literal — bundle text
// (backticks, `${`, backslashes, newlines) survives intact and byte-identical.
const contents =
  '// GENERATED by scripts/bundle-runtime.mjs — DO NOT EDIT.\n' +
  '// Regenerated by the package pre{build,typecheck,test} hooks.\n' +
  '/* eslint-disable */\n' +
  `export const cgJs = ${JSON.stringify(cgJs)};\n` +
  `export const cgJsIife = ${JSON.stringify(cgJsIife)};\n` +
  `export const cgJsLottie = ${JSON.stringify(cgJsLottie)};\n` +
  `export const cgJsLottieIife = ${JSON.stringify(cgJsLottieIife)};\n`;

await fs.promises.mkdir(OUT_DIR, { recursive: true });
// Atomic write: temp + rename so a concurrent reader never sees a partial file.
const tmp = `${OUT_FILE}.tmp-${String(process.pid)}`;
await fs.promises.writeFile(tmp, contents, 'utf-8');
await fs.promises.rename(tmp, OUT_FILE);

const kb = (s) => (Buffer.byteLength(s, 'utf-8') / 1024).toFixed(1);
console.error(
  `[bundle-runtime] wrote ${path.relative(PKG_ROOT, OUT_FILE)} ` +
    `(cgJs ${kb(cgJs)} KB, cgJsIife ${kb(cgJsIife)} KB, ` +
    `cgJsLottie ${kb(cgJsLottie)} KB, cgJsLottieIife ${kb(cgJsLottieIife)} KB)`,
);
